// nwdgeom extracts real geometry from a Navisworks .nwd file and writes it
// as a PLY point cloud (vertex coordinates). Triangle indices are not yet
// decoded (findings U21), so output is a point cloud.
//
// Usage: nwdgeom <file.nwd> <out.ply>
package main

import (
	"bufio"
	"fmt"
	"os"

	"github.com/flywave/go-nwd/nwd"
)

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: nwdgeom <file.nwd> <out.ply>")
		os.Exit(2)
	}
	buf, err := os.ReadFile(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
	f, err := nwd.Open(buf)
	if err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
	gi := f.StreamByName("LcOpNwdGeometry")
	if gi < 0 {
		fmt.Fprintln(os.Stderr, "no geometry stream")
		os.Exit(1)
	}
	blocks, err := f.DecodeGeometryVertices(gi, 0)
	if err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}

	out, err := os.Create(os.Args[2])
	if err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
	defer out.Close()
	w := bufio.NewWriter(out)
	defer w.Flush()

	total := 0
	for _, b := range blocks {
		total += len(b.Vertices)
	}
	fmt.Fprintln(w, "ply")
	fmt.Fprintln(w, "format ascii 1.0")
	fmt.Fprintf(w, "comment generated by go-nwd (geometry point cloud)\n")
	fmt.Fprintf(w, "element vertex %d\n", total)
	fmt.Fprintln(w, "property float x")
	fmt.Fprintln(w, "property float y")
	fmt.Fprintln(w, "property float z")
	fmt.Fprintln(w, "end_header")
	for _, b := range blocks {
		for _, v := range b.Vertices {
			fmt.Fprintf(w, "%.6f %.6f %.6f\n", v[0], v[1], v[2])
		}
	}
	fmt.Fprintf(os.Stderr, "wrote %d vertices in %d blocks\n", total, len(blocks))
}
